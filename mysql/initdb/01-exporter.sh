#!/bin/bash
# Sourced by the official MySQL entrypoint during the FIRST database initialization.
# setup.ps1 generates a hex password, so no quote escaping is required here.
set -e
if [[ ! "$MYSQL_EXPORTER_PASSWORD" =~ ^[A-Fa-f0-9]{32,}$ ]]; then
  echo 'MYSQL_EXPORTER_PASSWORD must be a strong hexadecimal value generated by setup.ps1' >&2
  exit 1
fi

docker_process_sql --database=mysql <<-EOSQL
CREATE USER IF NOT EXISTS 'metrics_user'@'%' IDENTIFIED BY '${MYSQL_EXPORTER_PASSWORD}';
GRANT PROCESS, REPLICATION CLIENT, SELECT ON *.* TO 'metrics_user'@'%';
EOSQL
